print("Operadores Aritiméticos")
print("Você irá informar dois números e o programa irá realizar as operações aritméticas básicas entre eles. \n")

n1 = int(input("Digite o primeiro número: "))
n2 = int(input("Digite o segundo número: "))

print(f"Soma: {n1} + {n2} = {n1 + n2}")
print(f"Subtração: {n1} - {n2} = {n1 - n2}")
print(f"Multiplicação: {n1} * {n2} = {n1 * n2}")
print(f"Divisão: {n1} / {n2} = {n1 / n2}")
print(f"Resto: {n1} % {n2} = {n1 % n2}")
print(f"Potência: {n1} ** {n2} = {n1 ** n2}")
print(f"Divisão Inteira: {n1} // {n2} = {n1 // n2}")

print()
