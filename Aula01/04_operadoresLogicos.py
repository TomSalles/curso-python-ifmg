print("Operadores Relacionais e de Comparação")
print("Eles nos retornam VERDADEIRO ou FALSO.")
print("== \t Igualdade")
print("!= \t Diferente")
print("< \t Menor que")
print("> \t Maior que")
print("<= \t Menor ou igual a")
print(">= \t Maior ou igual a")
print("not \t Negação || Ex: not True = False")

n1 = int(input("Digite o primeiro número: "))
n2 = int(input("Digite o segundo número: "))

print(f"{n1} == {n2} \t {n1 == n2}")
print(f"{n1} != {n2} \t {n1 != n2}")
print(f"{n1} < {n2} \t {n1 < n2}")
print(f"{n1} > {n2} \t {n1 > n2}")
print(f"{n1} <= {n2} \t {n1 <= n2}")
print(f"{n1} >= {n2} \t {n1 >= n2}")
print(f"not({n1} == {n2}) \t {not (n1 == n2)}")

